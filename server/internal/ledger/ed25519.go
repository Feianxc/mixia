// hasSmallOrder mirrors ge25519_has_small_order: the top bit, which only
// selects the sign of x, is ignored.
func hasSmallOrder(s []byte) bool {
	var masked [32]byte
	copy(masked[:], s)
	masked[31] &= 0x7f
	for _, bad := range smallOrderEncodings {
		if masked == bad {
			return true
		}
	}
	return false
}

// isCanonicalPoint mirrors ge25519_is_canonical: the low 255 bits must be below
// p = 2^255-19. The only values at or above p have 0xff in bytes 1 to 30, 0x7f
// in the masked top byte, and at least 0xed in byte 0.
func isCanonicalPoint(s []byte) bool {
	if s[31]&0x7f != 0x7f || s[0] < 0xed {
		return true
	}
	for _, b := range s[1:31] {
		if b != 0xff {
			return true
		}
	}
	return false
}

// validEd25519Pub reports whether libsodium will accept pub as a verification
// key at all.
func validEd25519Pub(pub []byte) bool {
	return len(pub) == ed25519.PublicKeySize && isCanonicalPoint(pub) && !hasSmallOrder(pub)
}

// StrictVerify is crypto_sign_verify_detached in Go. crypto/ed25519 alone is
// wider: it takes a small-order R or public key and a non-canonical public key.
// Clients verify every ledger entry with libsodium, so a signature only Go
// accepts would become an entry that no client can ever replay past.
func StrictVerify(pub, msg, sig []byte) bool {
	if len(sig) != ed25519.SignatureSize || !validEd25519Pub(pub) || hasSmallOrder(sig[:32]) {
		return false
	}
	return ed25519.Verify(pub, msg, sig)
}
